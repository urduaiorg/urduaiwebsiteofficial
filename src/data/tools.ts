// Quick lookup by name (case-insensitive)
const toolMap = new Map<string, Tool>();
tools.forEach(t => {
  toolMap.set(t.name.toLowerCase(), t);
  toolMap.set(t.urduName, t);
});

export function getToolByName(name: string): Tool | undefined {
  return toolMap.get(name.toLowerCase()) || toolMap.get(name);
}

export function getToolsByNames(names: string[]): Tool[] {
  return names
    .map(n => getToolByName(n))
    .filter((t): t is Tool => t !== undefined);
}

